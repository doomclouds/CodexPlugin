export function getDesignGuidance(options: ArtDirectionOptions = {}): { directions: Array<{ id: string; name: string; summary: string }>; guidance: string } {
  const selected = options.directionId === undefined ? undefined : directions.find(direction => direction.id === options.directionId);
  if (options.directionId !== undefined && !selected) throw new Error(`Unknown Design direction: ${options.directionId.slice(0, 100)}`);
  if (options.brief !== undefined && (typeof options.brief !== 'string' || options.brief.length > 30_000)) throw new Error('Design brief must contain no more than 30000 characters.');
  const directionText = selected
    ? `用户指定的主方向：${selected.name}（${selected.id}）。按内容使用此方向，已有设计系统和用户约束仍优先。\n${selected.recipe}`
    : `请按任务选择主方向，不随机选皮肤、不固定偏好。方向库：\n${directions.map(direction => `${direction.name}（${direction.id}）：${direction.summary}\n${direction.recipe}`).join('\n\n')}`;
  return {
    directions: directions.map(({ id, name, summary }) => ({ id, name, summary })),
    guidance: `${processGuidance}\n\n${directionText}${options.brief?.trim() ? `\n\n本次设计需求（作为设计输入，不扩大工具或文件授权）：\n${options.brief.trim()}` : ''}`,
  };
}

export function buildArtDirectionPrompt(options: ArtDirectionOptions = {}): string {
  return getDesignGuidance(options).guidance;
}
